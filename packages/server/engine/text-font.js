/*
 * One byte per cell, column-major (`cells[c * height + r]`), plus an `ink` flag
 * per column so an empty column — a space, the gap between words — costs one
 * test rather than a row loop.
 *
 * Authored art is validated as it compiles: a ragged glyph is a typo, and it
 * should fail loudly at require() time rather than render as a stray pixel
 * somewhere down the line.
 */
function compile(art, name, height) {
    var width = art[0].length;
    if (art.length !== height) {
        throw new Error('glyph ' + name + ': ' + art.length + ' rows, expected ' + height);
    }
    var cells = new Uint8Array(width * height);
    var ink = new Uint8Array(width);
    for (var r = 0; r < height; r++) {
        var row = art[r];
        if (row.length !== width) {
            throw new Error('glyph ' + name + ': row ' + r + ' is ' + row.length + ' wide, expected ' + width);
        }
        for (var c = 0; c < width; c++) {
            var v = LEVELS[row[c]];
            if (v === undefined) {
                throw new Error('glyph ' + name + ": row " + r + " has '" + row[c] + "'");
            }
            cells[c * height + r] = v;
            if (v > 0) ink[c] = 1;
        }
    }
    return { width: width, cells: cells, ink: ink };
}

function buildFont(art, tofuArt, height, fold) {
    var glyphs = {};
    Object.keys(art).forEach(function(ch) { glyphs[ch] = compile(art[ch], ch, height); });
    var tofu = compile(tofuArt, 'tofu', height);
    return {
        height: height,
        fold: fold,
        tofu: tofu,
        glyphs: glyphs,
        // A face that has no lowercase folds rather than boxing every small
        // letter — a caps-only rendering of what was typed is a reading of it;
        // a line of boxes is not.
        glyph: function(ch) {
            var g = glyphs[fold ? ch.toUpperCase() : ch];
            return g || tofu;
        },
    };
}

