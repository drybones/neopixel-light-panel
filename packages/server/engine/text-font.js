/*
 * The bitmap fonts behind the text effect, authored as rows of intensity
 * characters and compiled once at load into one byte per *cell*, column-major,
 * so laying out a line is a column-wise copy.
 *
 * One byte per cell rather than the obvious bit-per-cell, because a glyph cell
 * carries a *coverage*, not a switch. At 6x8 with a two-column stem a bowl drawn
 * in whole cells is a rectangle — there is no room for a curve — but the same
 * corner at 3/4 and 1/4 reads as one, for the reason a rasteriser antialiases
 * rather than snapping: the eye reconstructs the edge from the ratio. It costs
 * eight times the (trivial) glyph memory and turns a bit test into a byte read,
 * and it is what the `round` face is made of. The binary faces come through the
 * same path as cells that happen to be 0 or 255.
 *
 * Rows are the authoring form because a glyph has to be reviewable by eye;
 * columns are the storage form because that is the shape the renderer wants.
 * Glyph *width is the row length*, so variable width falls out of the art and
 * nothing declares it twice. One invariant test/text-font.test.js pins: every
 * digit within a face is the same width, or a clock reflows when the minute
 * rolls 19 -> 20.
 *
 * All four faces are seven or eight cap rows in an 8-row cell — the tallest cap
 * that still leaves somewhere for a descender to go, and the cell then maps 1:1
 * onto the panel with nothing to centre and no half-row offsets.
 *
 *   regular  5x7 caps, the whole printable ASCII range including lowercase.
 *            ~5 characters on the panel. The face to read as type.
 *   bold     6x7 caps, two-column stems, for a layer feeding a blend as a mask
 *            or a highlight: a one-LED stroke all but vanishes under a multiply
 *            and softness plus level only fakes the weight by dimming. No
 *            lowercase is drawable at that weight in a five-row x-height, so it
 *            folds to uppercase.
 *   heavy    6x8, bold's arms thickened to two rows — in `bold` a stem is two
 *            columns but a crossbar is one row, and E F H L Z wear that
 *            difference. Two-row arms need 2+1+2+1+2 rows to stack a top, middle
 *            and bottom bar, which is exactly 8, so this face gives up the
 *            descender row and in exchange is the one that is vertically centred
 *            by construction rather than sitting a row high.
 *   round    heavy's shapes with the curves drawn in partial cells. Flat-sided
 *            letters (E F H I L T) are byte-identical to heavy: there is nothing
 *            there to round and softening them would only lose contrast.
 *
 * Coverage: `regular` is complete for ASCII 32-126. The three caps-only faces
 * carry space, 0-9, A-Z and `: . , ' ! ? - " ( ) / + = %`. Anything else renders
 * as a hollow box — deliberately visible rather than silently missing.
 */

