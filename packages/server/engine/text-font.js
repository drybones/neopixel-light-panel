/*
 * The bitmap fonts behind the text effect, authored as rows of `.`/`#` and
 * compiled once at load into one byte per column (bit r = row r). Rows are the
 * authoring form because a glyph has to be reviewable by eye; columns are the
 * storage form because laying out a line is then a column-wise copy and
 * sampling it is a bit test. Every face is eight rows or fewer, so a column
 * always packs into one byte and an empty column is a zero — which is also the
 * skip test the sampler leans on for spaces and the wrap gap.
 *
 * Glyph *width is the row length*, so variable width falls out of the art and
 * nothing declares it twice. One invariant test/text-font.test.js pins: every
 * digit within a face is the same width, or a clock reflows when the minute
 * rolls 19 -> 20.
 *
 * The faces, light to heavy. All of them fit their caps in six or eight rows
 * with nothing hanging below, so only `regular` — the one face with lowercase —
 * needs a descender row at all.
 *
 *   micro     4x6, 1px stems. The smallest caps that still read; ~6 across.
 *   compact   5x6, 1px stems. Wider counters, still six rows.
 *   regular   5x7 caps with lowercase and the whole printable ASCII range.
 *             The face to read as type.
 *   grotesk   5x8, 1px stems. The same skeleton as `regular` given the eighth
 *             row: no extra weight, but the bowls stop being square.
 *   terminal  6x8, 1px stems. Legibility bought with width rather than weight.
 *   bold      6x8, 2px stems, 1px arms. The only weight above one pixel, and
 *             the one to reach for when the layer feeds a blend: a one-LED
 *             stroke all but vanishes under a multiply, and softness plus level
 *             only fake the weight by dimming.
 *
 * Coverage: `regular` is complete for ASCII 32-126. The caps-only faces carry
 * space, 0-9, A-Z and `! " % ' ( ) + , - . : = ? /`, and fold lowercase up
 * rather than boxing it. Anything else renders as a hollow box — deliberately
 * visible rather than silently missing.
 */

